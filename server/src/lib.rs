//! `rws-server`: SSR / SSG / 単一バイナリ配布のいずれのエントリからも
//! 共有される v1 共通コア（TASK-7.2 系）。
//!
//! 本クレートは v1 時点では [`router`] モジュール（パスマッチングルーター）
//! のみを提供する。HTTP サーバー本体（axum ハンドラ実装等、TASK-6.1c の
//! スコープ）・単一バイナリエントリ（TASK-9.1 のスコープ）はここに含めない。
//! `router` は HTTP・HTML を一切知らない純粋なパス解決ロジックであり、
//! それらのエントリ側が呼び出し側として組み込む前提の共通コアである。
//!
//! # 既定エスケープの引き継ぎ（REQ-1）
//!
//! 本クレート自身は HTML 文字列を一切組み立てない。ルート解決で得た
//! [`router::Params`] を画面へ出力する際は、呼び出し元が必ず `rws_core::text`
//! / `rws_core::el` の attrs 経由で既定エスケープを通すこと（router の
//! 契約はあくまで「生文字列を返す」ことまでであり、エスケープは行わない）。

